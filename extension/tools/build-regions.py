#!/usr/bin/env python3
"""Regenerate src/regions-data.js from Our World in Data's energy dataset (Ember data).

  curl -o /tmp/energy.csv https://raw.githubusercontent.com/owid/energy-data/master/owid-energy-data.csv
  curl -o /tmp/codes.csv  https://raw.githubusercontent.com/datasets/country-codes/main/data/country-codes.csv
  python3 tools/build-regions.py /tmp/energy.csv /tmp/codes.csv > src/regions-data.js

For each country it takes the latest year of:
  carbon_intensity_elec          lifecycle gCO2e per kWh of electricity generated (Ember)
  electricity_demand_per_capita  kWh of electricity demand per person per year, all uses (Ember)
"""
import csv, json, sys

energy_csv, codes_csv = sys.argv[1], sys.argv[2]
codes = {}
for r in csv.DictReader(open(codes_csv, encoding='utf-8')):
    a3, a2 = r['ISO3166-1-Alpha-3'], r['ISO3166-1-Alpha-2']
    if a3 and a2:
        codes[a3] = (a2, r['CLDR display name'] or r['official_name_en'])

latest = {}
for r in csv.DictReader(open(energy_csv, encoding='utf-8')):
    key = r['iso_code'] or ('WORLD' if r['country'] == 'World' else None)
    if not key:
        continue
    year = int(r['year'])
    for field in ('carbon_intensity_elec', 'electricity_demand_per_capita'):
        if r[field]:
            d = latest.setdefault(key, {})
            if field not in d or year > d[field][1]:
                d[field] = (float(r[field]), year)

out = {}
for key, d in latest.items():
    if 'carbon_intensity_elec' not in d or 'electricity_demand_per_capita' not in d:
        continue
    if key == 'WORLD':
        a2, name = 'WORLD', 'the world'
    elif key in codes:
        a2, name = codes[key]
    else:
        continue
    g, gy = d['carbon_intensity_elec']
    e, ey = d['electricity_demand_per_capita']
    if min(gy, ey) < 2015:   # too old to describe today's grid
        continue
    out[a2] = [name, round(g), gy, round(e), ey]

print('// Generated by tools/build-regions.py from Our World in Data / Ember. Do not edit by hand.')
print('// [name, grid gCO2e/kWh (lifecycle), year, electricity demand kWh per person per year, year]')
print('(function (root) {')
print('  var DATA = ' + json.dumps(dict(sorted(out.items())), ensure_ascii=False, separators=(',', ':')) + ';')
print("  if (typeof module === 'object' && module.exports) module.exports = DATA; else root.FootprintRegionData = DATA;")
print("})(typeof self !== 'undefined' ? self : this);")
